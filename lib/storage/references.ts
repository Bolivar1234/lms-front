const LESSON_RESOURCE_REFERENCE = /^lesson-resource:\/\/([1-9]\d*)\/([1-9]\d*)$/

export function parseLessonResourceReference(value: string): { lessonId: number; resourceId: number } | null {
  const match = LESSON_RESOURCE_REFERENCE.exec(value)
  if (!match) return null
  const lessonId = Number(match[1])
  const resourceId = Number(match[2])
  return Number.isSafeInteger(lessonId) && Number.isSafeInteger(resourceId) ? { lessonId, resourceId } : null
}

export function isLessonResourceReference(value: string): boolean {
  return parseLessonResourceReference(value) !== null
}

export function lessonResourceReference(lessonId: number, resourceId: number): string {
  if (![lessonId, resourceId].every((id) => Number.isSafeInteger(id) && id > 0)) throw new Error('Invalid resource identity')
  return `lesson-resource://${lessonId}/${resourceId}`
}

/** Storage keys are generated by the server, never accepted as an arbitrary URL. */
export function isScopedLessonResourcePath(path: string, tenantId: string, lessonId: number): boolean {
  const prefix = `${tenantId}/${lessonId}/`
  return path.startsWith(prefix) && /^[A-Za-z0-9_-]+\.[A-Za-z0-9]+$/.test(path.slice(prefix.length))
}
